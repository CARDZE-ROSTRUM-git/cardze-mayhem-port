#!/usr/bin/env python3
"""Generate the external-app source list and metadata registry for the host port.

Reads upstream firmware/application/external/external.cmake (the exact list the
device uses to build the external apps) and emits:
  * cmake/ExternalApps.cmake                     - source paths for the host build
  * platform/src/host_external_app_registry.inc  - the metadata symbol table

The metadata block of each app lives in its main.cpp as
_application_information_<name> with C linkage; the host loader walks the table
exactly like it walks SD-card .ppma files, so the display name, icon, colour and
menu location all come from the app's own upstream block.
"""
import re
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW = os.path.join(ROOT, "third_party/mayhem-firmware/firmware")
EXT = os.path.join(FW, "application/external")

cmake_txt = open(os.path.join(EXT, "external.cmake"), encoding="utf-8").read()

# Take only the EXTCPPSRC block, and only .cpp entries.
block = cmake_txt.split("set(EXTCPPSRC", 1)[1].split(")", 1)[0]
srcs = []
for line in block.splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    m = re.match(r"(external/[\w./-]+\.cpp)\s*$", line)
    if m:
        srcs.append(m.group(1))

# Derive the ordered, de-duplicated app list from the sources, preserving the
# upstream order (which is the menu ordering intent).
apps = []
seen = set()
for s in srcs:
    app = s.split("/")[1]
    if app not in seen:
        seen.add(app)
        apps.append(app)

# Map each app to its metadata symbol name by reading its main.cpp.
sym_of = {}
for app in apps:
    main_cpp = os.path.join(EXT, app, "main.cpp")
    if not os.path.exists(main_cpp):
        print(f"WARN: no main.cpp for {app}", file=sys.stderr)
        continue
    txt = open(main_cpp, encoding="utf-8").read()
    m = re.search(r"_application_information_[A-Za-z0-9_]+", txt)
    if not m:
        print(f"WARN: no metadata symbol in {app}/main.cpp", file=sys.stderr)
        continue
    sym_of[app] = m.group(0)

# --- cmake/ExternalApps.cmake ---
out = []
out.append("# Generated by tools/gen_external.py - do not edit by hand.")
out.append("# Verbatim upstream external-app sources (firmware/application/external),")
out.append("# compiled straight into the host binary so every menu tab is populated")
out.append("# without an SD card, exactly like the built-in games.")
out.append("set(MAYHEM_EXTERNAL_SOURCES")
out.append(f"    # {len(srcs)} source files across {len(apps)} external apps")
for s in srcs:
    out.append(f'    "${{MAYHEM_DIR}}/firmware/application/{s}"')
out.append(")")
open(os.path.join(ROOT, "cmake/ExternalApps.cmake"), "w", encoding="utf-8").write("\n".join(out) + "\n")

# --- registry .inc ---
inc = []
inc.append("/* Generated by tools/gen_external.py - do not edit by hand. */")
inc.append("/* Metadata table for every upstream external app, compiled into the host")
inc.append(" * binary. Each entry is the app's own _application_information_<name> block,")
inc.append(" * so the display name, icon, colour and menu location are the device's. */")
inc.append('extern "C" {')
for app in apps:
    if app in sym_of:
        inc.append(f"extern application_information_t {sym_of[app]};")
inc.append("}")
inc.append("")
inc.append("application_information_t* const builtin_apps[] = {")
for app in apps:
    if app in sym_of:
        inc.append(f"    &{sym_of[app]},  /* {app} */")
inc.append("};")
open(os.path.join(ROOT, "platform/src/host_external_app_registry.inc"), "w", encoding="utf-8").write("\n".join(inc) + "\n")

print(f"sources: {len(srcs)}  apps: {len(apps)}  symbols: {len(sym_of)}")
